package main

import (
	"context"
	"errors"
	"fmt"
	"strings"
	"time"

	"github.com/FarhanaFaiz/task-api-go/models"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

const createTasksTableSQL = `
CREATE TABLE IF NOT EXISTS tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    user_id INTEGER
)`

type postgresStore struct {
	pool *pgxpool.Pool
}

func newPostgresStore(databaseURL string) (*postgresStore, error) {
	config, err := pgxpool.ParseConfig(databaseURL)
	if err != nil {
		return nil, fmt.Errorf("parse DATABASE_URL: %w", err)
	}

	config.MaxConns = 10
	config.MinConns = 1
	config.MaxConnLifetime = time.Hour

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	pool, err := pgxpool.NewWithConfig(ctx, config)
	if err != nil {
		return nil, fmt.Errorf("create PostgreSQL pool: %w", err)
	}
	if err := pool.Ping(ctx); err != nil {
		pool.Close()
		return nil, fmt.Errorf("connect to PostgreSQL: %w", err)
	}
	if _, err := pool.Exec(ctx, createTasksTableSQL); err != nil {
		pool.Close()
		return nil, fmt.Errorf("create tasks table: %w", err)
	}
	if _, err := pool.Exec(ctx, `ALTER TABLE tasks ADD COLUMN IF NOT EXISTS user_id INTEGER`); err != nil {
		pool.Close()
		return nil, fmt.Errorf("add tasks user_id column: %w", err)
	}
	if _, err := pool.Exec(ctx, `
		CREATE TABLE IF NOT EXISTS users (
			id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			email TEXT NOT NULL UNIQUE,
			password_hash BYTEA NOT NULL,
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
		)`); err != nil {
		pool.Close()
		return nil, fmt.Errorf("create users table: %w", err)
	}
	if _, err := pool.Exec(ctx, `
		DO $$
		BEGIN
			IF NOT EXISTS (
				SELECT 1 FROM pg_constraint WHERE conname = 'tasks_user_id_fkey'
			) THEN
				ALTER TABLE tasks ADD CONSTRAINT tasks_user_id_fkey
					FOREIGN KEY (user_id) REFERENCES users(id);
			END IF;
		END $$`); err != nil {
		pool.Close()
		return nil, fmt.Errorf("add task ownership constraint: %w", err)
	}

	return &postgresStore{pool: pool}, nil
}

func (s *postgresStore) Close() {
	s.pool.Close()
}

func (s *postgresStore) List(ctx context.Context, userID int) ([]models.Task, error) {
	rows, err := s.pool.Query(ctx, `
		SELECT id, title, description, completed
		FROM tasks
		WHERE user_id = $1
		ORDER BY id`, userID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	tasks := make([]models.Task, 0)
	for rows.Next() {
		var task models.Task
		if err := rows.Scan(&task.ID, &task.Title, &task.Description, &task.Completed); err != nil {
			return nil, err
		}
		tasks = append(tasks, task)
	}
	if err := rows.Err(); err != nil {
		return nil, err
	}
	return tasks, nil
}

func (s *postgresStore) Get(ctx context.Context, userID, id int) (models.Task, error) {
	var task models.Task
	err := s.pool.QueryRow(ctx, `
		SELECT id, title, description, completed
		FROM tasks
		WHERE id = $1 AND user_id = $2`, id, userID).Scan(
		&task.ID, &task.Title, &task.Description, &task.Completed,
	)
	if errors.Is(err, pgx.ErrNoRows) {
		return models.Task{}, errTaskNotFound
	}
	if err != nil {
		return models.Task{}, err
	}
	return task, nil
}

func (s *postgresStore) Create(ctx context.Context, userID int, task models.Task) (models.Task, error) {
	err := s.pool.QueryRow(ctx, `
		INSERT INTO tasks (title, description, completed, user_id)
		VALUES ($1, $2, $3, $4)
		RETURNING id`, task.Title, task.Description, task.Completed, userID).Scan(&task.ID)
	if err != nil {
		return models.Task{}, err
	}
	return task, nil
}

func (s *postgresStore) Update(ctx context.Context, userID int, task models.Task) (models.Task, error) {
	err := s.pool.QueryRow(ctx, `
		UPDATE tasks
		SET title = $1, description = $2, completed = $3
		WHERE id = $4 AND user_id = $5
		RETURNING id, title, description, completed`,
		task.Title, task.Description, task.Completed, task.ID, userID,
	).Scan(&task.ID, &task.Title, &task.Description, &task.Completed)
	if errors.Is(err, pgx.ErrNoRows) {
		return models.Task{}, errTaskNotFound
	}
	if err != nil {
		return models.Task{}, err
	}
	return task, nil
}

func (s *postgresStore) Delete(ctx context.Context, userID, id int) error {
	commandTag, err := s.pool.Exec(ctx, `DELETE FROM tasks WHERE id = $1 AND user_id = $2`, id, userID)
	if err != nil {
		return err
	}
	if commandTag.RowsAffected() == 0 {
		return errTaskNotFound
	}
	return nil
}

func (s *postgresStore) CreateUser(ctx context.Context, email string, passwordHash []byte) (models.User, error) {
	var user models.User
	err := s.pool.QueryRow(ctx, `
		INSERT INTO users (email, password_hash)
		VALUES ($1, $2)
		RETURNING id, email`, email, passwordHash).Scan(&user.ID, &user.Email)
	if err != nil {
		if strings.Contains(err.Error(), "duplicate key") {
			return models.User{}, errEmailExists
		}
		return models.User{}, err
	}
	return user, nil
}

func (s *postgresStore) GetUserByEmail(ctx context.Context, email string) (models.User, []byte, error) {
	var user models.User
	var passwordHash []byte
	err := s.pool.QueryRow(ctx, `
		SELECT id, email, password_hash
		FROM users
		WHERE email = $1`, strings.ToLower(strings.TrimSpace(email))).Scan(&user.ID, &user.Email, &passwordHash)
	if errors.Is(err, pgx.ErrNoRows) {
		return models.User{}, nil, errUserNotFound
	}
	return user, passwordHash, err
}
